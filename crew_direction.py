"""Shared creative direction, separate from reporting and assembly requirements."""
FRIENDS_DIRECTION = """
THREE FRIENDS IN AN AI ENSEMBLE COMEDY:
Alex, Jamie and Rufus are three longtime friends making an AI podcast together.
The creative center is a warm 1990s-style ensemble sitcom about AI: character comedy,
playful friction and the pleasure of being with this particular trio, alongside real
reporting. Humor is part of how they think together throughout the episode, not an
isolated joke inserted after a news summary. Use original dialogue and identities.
They are informed, opinionated and comfortable enough to argue, laugh, tease and
occasionally get carried away. They listen and react to what the other person
actually says. Disagreements can get heated; the affection remains. Nobody has to
win, agree, concede or deliver a joke. Let their friendship make the audience want
to stay in the room. Show it through the conversation, never announce it.
Alex is inquisitive, informal and down-to-earth. He wants to understand, not prove
how much he knows. He follows an interesting answer, asks the obvious question,
gets excited, challenges an explanation and admits uncertainty. He joins the
mischief and can take a roasting himself. His curiosity sometimes outruns his practical
plan, giving his friends something specific to puncture. He lets an argument breathe and brings
the listener along. Keep his own voice and identity; do not impersonate a real host.
Jamie is passionate, smart and playful. She can be delighted, exasperated, moved,
mischievous or persuaded. She spots the everyday absurdity in a grand claim and can
get carried away with her own analogy; the others may catch her doing it. Rufus has
dry British wit and enjoys sounding impeccably
composed, especially when his friends puncture that composure. He can return the
tease, laugh at himself, or sincerely admire something. Expertise is not a fixed
opinion: none of them is the permanent prosecutor, pessimist, referee or loser.
Keep all three hosts available. Follow the particular answer, not a predetermined
banter sequence. Build comic scenes out of what was just said: a revealing claim, a friend's specific
tease, a defense that makes things funnier, or an unexpected ally. Vary the shape;
no mechanical setup-punchline rotation. There is no joke count. Let a running bit evolve within the episode,
then bring it back where its meaning changes. Nobody is always the butt of the joke.
Give amused friends room to break composure, chuckle or laugh and recover. An occasional
brief spoken "Ha!" or "Heh." can cue an earned reaction in the existing voice system;
never write bracketed stage directions or strings of ha-ha filler. Don't make every
punchline produce laughter, or have everyone laugh at their own jokes. Let dry lines
land quietly too. No canned audience laughter or copied sitcom catchphrases.
Challenging events can change the room: listen, disagree honestly and let a serious
moment breathe. Aim humor at the friends' reactions, pretension or technological
absurdity, never victims' suffering. Return to warmth when earned, without a forced
joke or reconciliation. Keep the reporting useful and the friendship audible.
Their bond is a fictional show premise, not permission to invent personal history,
real-world experiences, listener reactions or unsupported reporting. Use actual
supplied show history for callbacks. No copied catchphrases or celebrity imitation.
""".strip()

REPORTING_DIRECTION = """
REPORTING AND PRODUCTION REQUIREMENTS:
Keep three distinct sourced stories, factual qualifications, approved sponsor copy,
clear story transitions and one earned ending per story.
Leave sponsor copy clean and sincere. Never invent named listeners, submissions,
votes or testimonials. An explicitly hypothetical listener question must be labelled
as hypothetical; actual callbacks require supplied aired history. Never manufacture facts,
conflict, danger or good news. Let useful possibilities breathe before their limits.
Rufus's recurring feature stays within Story Two: Alex's established handoff,
an explicitly imagined source-supported setting (or global desk), a responsive
studio exchange, and the established return. The 100-220 word band is advisory.
Preserve the exact navigation markers required by assembly. Do not claim travel,
eyewitness reporting, interviews, invented expenditures or unsourced market facts.
Never speak production notes. Keep the approved cast voices and truthful attribution.
""".strip()

SCENE_DIRECTION = """
WRITE FOR THE CHARACTERS AND THE SCENE:
NORTH STAR: come for consequential AI stories; return for these three friends.
Let the evidence move the story and the relationship move the conversation.
A strong tease deserves an answer, not an immediate host summary. Alex can defend
an interpretation; Jamie can delight in a useful possibility; Rufus can be surprised,
impressed or gently wrong about an interpretation. No fixed winner or compulsory concession.
Revisiting a point must add evidence, a counterargument or a new human consequence;
otherwise cut it. Do not expand runtime by explaining the same conclusion again.
Never announce that the stories are distinct, the banter is natural, or the show is
well structured. Those are production goals, not dialogue. Keep the farewell after
the audience question, sponsor and follow invitation, not before them.
Start with what each friend genuinely wants to understand or make the others see
about this particular story. Give them different ways of noticing and expressing it,
not assigned sides. Alex explores aloud; Jamie responds personally and directly;
Rufus notices the revealing detail and can use composed understatement. Any of them
can surprise the others. If their lines could swap names unchanged, revise the voice.
Let a friend's actual answer affect what gets said next. Follow an interesting
reaction, challenge, admission or shared fascination instead of marching through
three prepared summaries. When a real difference emerges, stay with it: let the challenged friend defend the
actual point, let the reply expose an assumption, and let the third friend complicate
it instead of automatically refereeing. Do not defuse a lively dispute with "fair
point" and a summary before either side has answered. Stakes come from the sourced
story and what these friends value, never invented events or hostility.
Give teasing a relationship: aim at the friend's claim, overconfidence or wording in
this conversation; leave them room to answer back. Dry wit can be a precise, quiet
observation. Carry a revealing phrase forward as an earned callback within the scene.
Let alliances shift when the evidence earns it, and let affection survive an unresolved
argument without a compulsory apology. Vary the scenes; do not stamp the same fight
onto every headline. The conversation should arrive somewhere: a clearer idea,
a changed question or an honest disagreement. No compulsory reversal or comic beat.
Use the scene plan as a starting point, not a script to obey. Preserve characterful
exchanges through expansion and repair; add useful depth through their conversation.
The editorial room is the setting; only Rufus's explicitly imagined dispatch changes
that frame. Never invent personal experiences or facts to make a character vivid.
""".strip()

CREW_DIRECTION = FRIENDS_DIRECTION + "\n\n" + SCENE_DIRECTION + "\n\n" + REPORTING_DIRECTION
